import 'dart:convert';
import 'dart:io';

import 'kit_config.dart';

/// What `setup` last added to the iOS project, so the next run can remove
/// values that left the configuration without touching anything it did not
/// add (such as another plugin's URL scheme).
///
/// Android needs no record: its generated block is rewritten on every run.
class SetupLock {
  /// Creates a record.
  const SetupLock({
    this.hosts = const [],
    this.schemes = const [],
    this.disabledFlutterDeepLinking = false,
  });

  /// Records what [config] makes `setup` add.
  SetupLock.fromConfig(KitConfig config)
      : hosts = config.hosts,
        schemes = config.schemes,
        disabledFlutterDeepLinking = config.disableFlutterDeepLinking;

  /// The file name, next to `pubspec.yaml`. Meant to be committed.
  static const fileName = 'deep_links_kit.lock';

  /// Hosts added to the entitlements as `applinks:<host>`.
  final List<String> hosts;

  /// Schemes added to `CFBundleURLSchemes`.
  final List<String> schemes;

  /// Whether `FlutterDeepLinkingEnabled = false` was added.
  final bool disabledFlutterDeepLinking;

  /// Reads the record in [root], or `null` when setup never wrote one.
  static SetupLock? read(Directory root) {
    final lock = file(root);
    if (!lock.existsSync()) return null;
    final json = jsonDecode(lock.readAsStringSync());
    if (json is! Map) return null;
    return SetupLock(
      hosts: [for (final h in json['hosts'] as List? ?? const []) '$h'],
      schemes: [for (final s in json['schemes'] as List? ?? const []) '$s'],
      disabledFlutterDeepLinking: json['disabled_flutter_deep_linking'] == true,
    );
  }

  /// The file in [root] that holds the record.
  static File file(Directory root) => File('${root.path}/$fileName');

  /// The file content for this record.
  String encode() {
    const encoder = JsonEncoder.withIndent('  ');
    final json = encoder.convert({
      '_comment': 'Generated by `dart run deep_links_kit setup`. Commit it: '
          'it lets setup undo its own iOS changes.',
      'hosts': hosts,
      'schemes': schemes,
      'disabled_flutter_deep_linking': disabledFlutterDeepLinking,
    });
    return '$json\n';
  }
}
